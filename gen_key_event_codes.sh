#!/bin/sh
#
# Generate the keyboard name/code table from the system's Linux UAPI header.
# Usage: CC=gcc ./gen_key_event_codes.sh > key_event_codes.c
#
# Copyright (c) 2026, paul-1 <6473457+paul-1@users.noreply.github.com>
# SPDX-License-Identifier: BSD-3-Clause

set -e
CC=${CC:-cc}

names=$(printf '#include <linux/input-event-codes.h>\n' | $CC -dM -E - |
	awk '$1 == "#define" && $2 ~ /^KEY_[A-Z0-9_]+$/ &&
	     $2 != "KEY_MAX" && $2 != "KEY_CNT" { print $2 }' | LC_ALL=C sort -u)

if [ -z "$names" ]; then
	echo "No KEY_ definitions found in linux/input-event-codes.h" >&2
	exit 1
fi

echo '/* Generated by gen_key_event_codes.sh from linux/input-event-codes.h. */'
echo '#include <linux/input-event-codes.h>'
echo '#include "control.h"'
echo
echo 'const key_events_s key_codes[] = {'
# Unknown names fall back to the first entry, KEY_RESERVED (0).
echo '	{ "KEY_RESERVED", KEY_RESERVED },'
for name in $names; do
	[ "$name" = KEY_RESERVED ] && continue
	# init_uinput() enables key codes 0-254 only.
	echo "#if $name < 255"
	echo "	{ \"$name\", $name },"
	echo '#endif'
done
echo '	{ "", -1 }'
echo '};'
